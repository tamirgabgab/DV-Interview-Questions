# --- the bonus: four digits in base B ------------------------------------------------------

RLM = "‏"
DIG = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def digits_b(x, B):
    return [x // B ** 3, x // B ** 2 % B, x // B % B, x % B]


def text_b(x, B):
    return "".join(DIG[v] for v in digits_b(x, B))


def step_b(x, B):
    a, b, c, d = sorted(digits_b(x, B), reverse=True)
    return (a * B ** 3 + b * B ** 2 + c * B + d) - (d * B ** 3 + c * B ** 2 + b * B + a)


def pair_b(x, B):
    """(p, q): the largest digit minus the smallest, and the two middle digits' difference."""
    a, b, c, d = sorted(digits_b(x, B), reverse=True)
    return a - d, b - c


def value_b(p, q, B):
    return p * (B ** 3 - 1) + q * (B ** 2 - B)


def fixed_b(B):
    """The fixed points with two different digits, by the theorem."""
    out = []
    if B == 2:
        out += [7, 9]                                   # 0111 and 1001
    if B == 4:
        out += [3 * 64 + 2 * 4 + 1]                     # 3021
    if B % 5 == 0:
        out.append(B * (B - 1) * (3 * B * B + 4 * B + 3) // 5)
    return sorted(out)


def orbit_b(x, B):
    """The values from x until one repeats: (values, index where the cycle starts)."""
    vals = [x]
    while True:
        y = step_b(vals[-1], B)
        if y in vals:
            return vals, vals.index(y)
        vals.append(y)


def attractors_b(B):
    """Every cycle of the step (a fixed point is a cycle of length 1) with the number of
    the B^4 numbers that end in it, largest basin first; 0 included."""
    found = {}
    for x in range(B ** 4):
        vals, i = orbit_b(x, B)
        key = min(vals[i:])
        if key not in found:
            cyc, v = [key], step_b(key, B)
            while v != key:
                cyc.append(v)
                v = step_b(v, B)
            found[key] = [cyc, 0]
        found[key][1] += 1
    return sorted(found.values(), key=lambda t: (-t[1], t[0][0]))


FAMILY = range(5, 55, 5)
EXAMPLE_B, EXAMPLE_X = 15, 1 * 15 ** 3 + 2 * 15 ** 2 + 3 * 15 + 4      # 1234 in base 15


def theorem_table():
    lines = ["| הבסיס B | נקודת השבת בבסיס B | הערך העשרוני |", "|:-:|:-:|:-:|"]
    lines.append(f"| {RLM}2 | {RLM}0111 ו-1001 | {RLM}7 ו-9 |")
    lines.append(f"| {RLM}4 | {RLM}3021 | {RLM}201 |")
    lines.append(f"| {RLM}**B = 5k** | {RLM}**(3k, k − 1, 4k − 1, 2k)** | {RLM}**B(B − 1)(3B² + 4B + 3) / 5** |")
    lines.append("| כל בסיס אחר | אין | — |")
    return "\n".join(lines)


def family_table():
    lines = ["| ‏B | ‏k | הספרות | בבסיס B | הערך העשרוני |", "|:-:|:-:|:-:|:-:|:-:|"]
    for B in FAMILY:
        k = B // 5
        x = fixed_b(B)[-1]
        assert digits_b(x, B) == [3 * k, k - 1, 4 * k - 1, 2 * k]
        shown = f"**{text_b(x, B)}**" if B <= 36 else "—"
        lines.append(f"| {RLM}{B} | {RLM}{k} | {RLM}({3 * k}, {k - 1}, {4 * k - 1}, {2 * k}) | {RLM}{shown} | {RLM}{x:,} |")
    return "\n".join(lines)


def example_table(x0=EXAMPLE_X, B=EXAMPLE_B):
    vals, start = orbit_b(x0, B)
    lines = [f"| צעד | ‏X בבסיס {B} | מהגדול לקטן | מהקטן לגדול | ‏(p, q) | ההפרש |", "|:-:|:-:|:-:|:-:|:-:|:-:|"]
    for i, x in enumerate(vals, 1):
        ds = sorted(digits_b(x, B), reverse=True)
        big = sum(v * B ** (3 - j) for j, v in enumerate(ds))
        small = sum(v * B ** j for j, v in enumerate(ds))
        y = step_b(x, B)
        p, q = pair_b(x, B)
        lines.append(f"| {RLM}{i} | {RLM}{text_b(x, B)} | {RLM}{text_b(big, B)} | {RLM}{text_b(small, B)} | {RLM}({p}, {q}) | {RLM}**{text_b(y, B)}** |")
    return "\n".join(lines)


def attractor_table(bases=range(2, 17)):
    lines = ["| ‏B | נקודות שבת | מחזורים : האורך (כמה מספרים מגיעים) | מגיעים לנקודת שבת |", "|:-:|:-:|---|:-:|"]
    for B in bases:
        att = [(c, n) for c, n in attractors_b(B) if c != [0]]
        fixed = [(c, n) for c, n in att if len(c) == 1]
        cycles = [(c, n) for c, n in att if len(c) > 1]
        fx = ", ".join(text_b(c[0], B) for c, _ in fixed) or "—"
        cy = ", ".join(f"{len(c)} ({n:,})" for c, n in cycles) or "—"
        into = sum(n for _, n in fixed)
        total = B ** 4 - B
        lines.append(f"| {RLM}{B} | {RLM}{fx} | {RLM}{cy} | {RLM}{into:,} מתוך {total:,} |")
    return "\n".join(lines)


def pair_map_svg(B=EXAMPLE_B, x0=EXAMPLE_X):
    """The pairs (p, q) with p >= 1 as a triangle (rows p, columns q): each cell coloured by
    where its value ends (the fixed point, a cycle, or on a cycle itself), and the path of
    the example as arrows from pair to pair."""
    CW, CH, X0, Y0 = 26, 22, 44, 26
    W, H = X0 + B * CW + 8, Y0 + (B - 1) * CH + 8
    fixed = set(fixed_b(B))
    on_cycle, to_fixed = set(), set()
    for p in range(1, B):
        for q in range(p + 1):
            vals, i = orbit_b(value_b(p, q, B), B)
            if len(vals) - i == 1 and vals[i] in fixed:
                to_fixed.add((p, q))
            if value_b(p, q, B) in vals[i:]:
                on_cycle.add((p, q))
    cx = lambda q: X0 + q * CW + CW / 2           # noqa: E731
    cy = lambda p: Y0 + (p - 1) * CH + CH / 2     # noqa: E731
    out = [f'<svg class="figure kq-map" viewBox="0 0 {W} {H}" style="max-width:{W / 16:.0f}rem" role="img" '
           f'aria-label="המפה של הזוגות (p, q) בבסיס {B} : כל משבצת צבועה לפי היעד של הערך שלה, והמסלול של {text_b(x0, B)}">']
    for q in range(B):
        out.append(f'<text class="kq-tick" x="{cx(q):.0f}" y="{Y0 - 8}" text-anchor="middle">{q}</text>')
    out.append(f'<text class="kq-tick" x="{X0 - 30}" y="{Y0 - 8}">p \\ q</text>')
    for p in range(1, B):
        out.append(f'<text class="kq-tick" x="{X0 - 6}" y="{cy(p) + 4:.0f}" text-anchor="end">{p}</text>')
        for q in range(p + 1):
            v = value_b(p, q, B)
            cls = "is-fixed" if v in fixed and pair_b(v, B) == (p, q) else "is-cycle" if (p, q) in on_cycle else "to-fixed" if (p, q) in to_fixed else "to-cycle"
            out.append(f'<rect class="kq-cell {cls}" x="{X0 + q * CW + 1}" y="{Y0 + (p - 1) * CH + 1}" width="{CW - 2}" height="{CH - 2}" rx="3">'
                       f'<title>(p, q) = ({p}, {q}) : {text_b(v, B)}</title></rect>')
    vals, start = orbit_b(x0, B)
    pairs = [pair_b(x, B) for x in vals] + [pair_b(step_b(vals[-1], B), B)]
    for (p1, q1), (p2, q2) in zip(pairs, pairs[1:]):
        out.append(f'<line class="kq-path" x1="{cx(q1):.1f}" y1="{cy(p1):.1f}" x2="{cx(q2):.1f}" y2="{cy(p2):.1f}"/>'
                   f'<circle class="kq-head" cx="{cx(q2):.1f}" cy="{cy(p2):.1f}" r="3.5"/>')
    p0, q0 = pairs[0]
    out.append(f'<circle class="kq-start" cx="{cx(q0):.1f}" cy="{cy(p0):.1f}" r="7"/></svg>')
    return "".join(out)


def pair_map_legend():
    return ('<span class="viz-legend"><span><i class="kq-key-fixed"></i>נקודת השבת 92B6 : ‏(p, q) = (9, 3)</span>'
            '<span><i class="kq-key-cycle"></i>זוגות שעל מחזור</span>'
            '<span><i class="kq-key-tofixed"></i>מגיעים לנקודת השבת</span>'
            '<span><i class="kq-key-tocycle"></i>נכנסים למחזור</span>'
            '<span><i class="kq-key-path"></i>המסלול של 1234 (העיגול : ההתחלה)</span></span>')


def blocks():
    """The generated blocks of the bonus, in page order."""
    return [theorem_table(), family_table(), example_table(), attractor_table(), pair_map_svg(), pair_map_legend()]


